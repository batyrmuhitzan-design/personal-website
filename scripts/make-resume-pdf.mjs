// ---------------------------- 排版 ----------------------------
let y = PAGE_H - MARGIN;
rows.forEach((row) => {
  y -= row.gap;
  if (y < MARGIN) {
    throw new Error("内容超出一页，请精简简历内容");
  }
  if (row.rule) {
    rect(MARGIN, y, PAGE_W - MARGIN * 2, 1.2, ACCENT);
  } else {
    text(row.f, row.s, MARGIN, y, row.t, row.c);
  }
});

const content = ops.join("\n");

// ---------------------------- 组装 PDF ----------------------------
const objects = {
  1: "<< /Type /Catalog /Pages 2 0 R >>",
  2: "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
  3:
    `<< /Type /Page /Parent 2 0 R /MediaBox [0 0 ${PAGE_W} ${PAGE_H}] ` +
    "/Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> /Contents 4 0 R >>",
  4: `<< /Length ${Buffer.byteLength(content, "latin1")} >>\nstream\n${content}\nendstream`,
  5: "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>",
  6: "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>",
  7:
    "<< /Title (Shasha - Web Developer & Automation Specialist) /Author (Shasha) " +
    "/Creator (make-resume-pdf.mjs) /Producer (make-resume-pdf.mjs) >>",
};

const total = Object.keys(objects).length + 1; // 含 0 号空闲对象
let pdf = "%PDF-1.4\n";
const offsets = [];

for (let i = 1; i < total; i += 1) {
  offsets[i] = Buffer.byteLength(pdf, "latin1");
  pdf += `${i} 0 obj\n${objects[i]}\nendobj\n`;
}

const xrefOffset = Buffer.byteLength(pdf, "latin1");
let xref = `xref\n0 ${total}\n0000000000 65535 f \n`;
for (let i = 1; i < total; i += 1) {
  xref += `${String(offsets[i]).padStart(10, "0")} 00000 n \n`;
}
pdf += xref;
pdf += `trailer\n<< /Size ${total} /Root 1 0 R /Info 7 0 R >>\nstartxref\n${xrefOffset}\n%%EOF\n`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, Buffer.from(pdf, "latin1"));

// ---------------------------- 结构自检 ----------------------------
const written = readFileSync(outFile);
const raw = written.toString("latin1");
const startxref = Number(
  raw.slice(raw.lastIndexOf("startxref") + 9).trim().split("\n")[0]
);
const ok =
  raw.startsWith("%PDF-1.4") &&
  raw.trimEnd().endsWith("%%EOF") &&
  raw.slice(startxref, startxref + 4) === "xref" &&
  raw.includes("/BaseFont /Helvetica");

if (!ok) {
  throw new Error("PDF 结构自检失败，请检查生成逻辑");
}

