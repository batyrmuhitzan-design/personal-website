import { mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, "../src/Assets/Shasha_Resume.pdf");

const PAGE_W = 595;
const PAGE_H = 842;
const MARGIN = 56;
const ACCENT = "0.067 0.067 0.067"; // #111111 —— 黑白灰强调色（与站点令牌一致）
const DARK = "0.067 0.067 0.067"; // #111111 主文字
const GREY = "0.4 0.4 0.4"; // 中性灰次要文字

/** 转义 PDF 字符串的特殊字符 */
const esc = (s) =>
  String(s)
    .replace(/\\/g, "\\\\")
    .replace(/\(/g, "\\(")
    .replace(/\)/g, "\\)");

const ops = [];

/** 写入一行文本 */
const text = (font, size, x, y, value, color = DARK) => {
  ops.push(`${color} rg`);
  ops.push(`BT /${font} ${size} Tf ${x} ${y} Td (${esc(value)}) Tj ET`);
};

/** 写入一个填充矩形（用于分隔线） */
const rect = (x, y, w, h, color) => {
  ops.push(`${color} rg ${x} ${y} ${w} ${h} re f`);
};

